"""
Comparing flowsheets constructed with surrogate models for multi-component
diafiltration model at different length scales.

Three representations of the same 5-tube diafiltration stage are compared:
  1. the high-fidelity first-principles stage (reference data, generated by
     generate_synthetic_data.py for the training conditions and by
     generate_stage_test_data.py for held-out conditions),
  2. a single Kriging surrogate of the whole stage (stage scale), and
  3. a chain of five Kriging tube surrogates (tube scale), connected by overall
     and solute mass balances, with the diafiltrate stream mixed into the feed
     of tube 4.

The tube surrogate predicts the tube-average cation flux and (the log of) the
tube-average water flux. The water flux gives the permeate flow, and the cation
flux gives the retentate concentration:
    F_ret = F_in - A * J_w
    F_ret * c_ret = F_in * c_in - A * J_s
where A is the membrane area of a tube.

Author: Molly Dougher, Claude
"""

import os
import time

import numpy as np
import pandas as pd

import matplotlib.pyplot as plt

from pyomo.environ import (
    ConcreteModel,
    Constraint,
    Expression,
    RangeSet,
    SolverFactory,
    Var,
    assert_optimal_termination,
    exp,
    value,
)

from idaes.core import FlowsheetBlock
from idaes.core.surrogate.pysmo_surrogate import PysmoSurrogate
from idaes.core.surrogate.surrogate_block import SurrogateBlock
from idaes.core.util.model_statistics import (
    degrees_of_freedom,
    number_total_constraints,
    number_variables,
)

HERE = os.path.dirname(os.path.abspath(__file__))

TUBE_SURROGATE_FILE = os.path.join(
    HERE, "surrogate_models/tube/single_salt/single_salt_kriging_surrogate"
)
STAGE_SURROGATE_FILE = os.path.join(
    HERE, "surrogate_models/stage/single_salt/single_salt_kriging_surrogate"
)

NUM_TUBES = 5
PRESSURE_DROP = 0.5  # bar per tube
FEED_FLOW = 17  # m3/h, feed to tube 1
MEMBRANE_AREA = 164  # m2 per tube = total_module_length (4 m) x total_membrane_length (41 m)

# diafiltrate stream, added to the feed of tube 4 (same as the high-fidelity data)
DIAFILTRATE_TUBE = 4
DIAFILTRATE_CONC = 10  # mol/m3 of cation
DIAFILTRATE_FLOW = {1: 5, 2: 5, 3: 2.5}  # m3/h by cation valence (Na, Ca, La)

CATION = {1: "Na", 2: "Ca", 3: "La"}

OUTPUT_FOLDER = os.path.join(HERE, "figures/comparison")


def main():
    os.makedirs(OUTPUT_FOLDER, exist_ok=True)

    tube_surrogate = PysmoSurrogate.load_from_file(TUBE_SURROGATE_FILE)
    stage_surrogate = PysmoSurrogate.load_from_file(STAGE_SURROGATE_FILE)

    results, tube_details = compare_flowsheets(tube_surrogate, stage_surrogate)
    results.to_csv(f"{OUTPUT_FOLDER}/comparison_results.csv", index=False)
    tube_details.to_csv(f"{OUTPUT_FOLDER}/comparison_tube_details.csv", index=False)

    summary = summarize(results, tube_details)
    summary.to_csv(f"{OUTPUT_FOLDER}/comparison_summary.csv")
    print(summary.to_string(float_format=lambda x: f"{x:.4g}"))

    size = model_size_table(tube_surrogate, stage_surrogate)
    size.to_csv(f"{OUTPUT_FOLDER}/comparison_model_size.csv")
    print(size.to_string())

    cost = training_cost_table()
    cost.to_csv(f"{OUTPUT_FOLDER}/comparison_training_cost.csv")
    print(cost.to_string())

    plot_comparison(results)
    plt.show()


