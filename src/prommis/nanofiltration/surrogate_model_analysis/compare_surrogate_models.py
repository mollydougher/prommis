def load_high_fidelity_data():
    """Stage and per-tube high-fidelity data for the training and test conditions."""
    data = {}
    for label, folder in (("training", "training_data"), ("test", "test_data")):
        base = os.path.join(HERE, folder, "stage/single_salt")
        stage_file = os.path.join(base, "mixed_chlorides")
        tube_file = os.path.join(base, "mixed_chlorides_tube_conditions")
        if os.path.exists(stage_file) and os.path.exists(tube_file):
            data[label] = (pd.read_csv(stage_file), pd.read_csv(tube_file))
        else:
            print(f"No high-fidelity {label} data found in {base}; skipping")
    return data


def compare_flowsheets(tube_surrogate, stage_surrogate):
    rows = []
    tube_rows = []

    for label, (stage_data, tube_data) in load_high_fidelity_data().items():
        for _, point in stage_data.iterrows():
            valence = int(point["valency"])
            feed_conc = float(point["feed_conc"])
            pressure = float(point["pressure"])
            hf_flux = float(point["ion_flux"])
            print(f"{label}: {CATION[valence]}, c = {feed_conc}, P = {pressure}")

            row = {
                "set": label,
                "cation": CATION[valence],
                "valency": valence,
                "feed_conc": feed_conc,
                "pressure": pressure,
                "hf_flux": hf_flux,
                # warm-started continuation solve time (not available for points
                # whose time includes a fresh build)
                "hf_warm_solve_time_s": (
                    point["solve_time_s"]
                    if "solve_time_s" in point and point.get("from_scratch", 0) == 0
                    else np.nan
                ),
            }

            # stage surrogate
            try:
                m = build_stage_surrogate_flowsheet(
                    valence, feed_conc, pressure, stage_surrogate
                )
                row["stage_solve_time_s"] = solve_flowsheet(m)
                row["stage_flux"] = value(m.fs.flux_cation)
                row["stage_n_variables"] = number_variables(m)
                row["stage_n_constraints"] = number_total_constraints(m)
            except Exception as e:
                row["stage_flux"] = np.nan
                row["stage_status"] = str(e).splitlines()[0][:80]

            # chain of tube surrogates
            try:
                m = build_tube_surrogate_flowsheet(
                    valence, feed_conc, pressure, tube_surrogate
                )
                row["chain_solve_time_s"] = solve_flowsheet(m)
                row["chain_flux"] = value(m.fs.stage_average_flux)
                row["chain_n_variables"] = number_variables(m)
                row["chain_n_constraints"] = number_total_constraints(m)
                row["chain_extrapolation"] = tube_input_extrapolation(m, tube_surrogate)

                hf_tubes = tube_data[
                    (tube_data["valency"] == valence)
                    & np.isclose(tube_data["tube_1_feed_conc"], feed_conc)
                    & np.isclose(tube_data["tube_1_pressure"], pressure)
                ]
                for _, hf in hf_tubes.iterrows():
                    i = int(hf["tube"])
                    tube_rows.append(
                        {
                            "set": label,
                            "cation": CATION[valence],
                            "feed_conc": feed_conc,
                            "pressure": pressure,
                            "tube": i,
                            "hf_inlet_flow": hf["tube_inlet_flow"],
                            "chain_inlet_flow": value(m.fs.feed_flow[i]),
                            "hf_inlet_conc": hf["tube_inlet_conc"],
                            "chain_inlet_conc": value(m.fs.feed_conc_cation[i]),
                            "hf_flux": hf["tube_ion_flux"],
                            "chain_flux": value(m.fs.flux_cation[i]),
                            "hf_water_flux": hf["tube_water_flux"],
                            "chain_water_flux": value(m.fs.water_flux[i]),
                        }
                    )
            except Exception as e:
                row["chain_flux"] = np.nan
                row["chain_status"] = str(e).splitlines()[0][:80]

            rows.append(row)

    results = pd.DataFrame(rows)
    for model in ("stage", "chain"):
        results[f"{model}_percent_error"] = (
            100 * (results[f"{model}_flux"] - results["hf_flux"]) / results["hf_flux"]
        )

    tube_details = pd.DataFrame(tube_rows)
    for quantity in ("inlet_flow", "inlet_conc", "flux", "water_flux"):
        tube_details[f"{quantity}_percent_error"] = (
            100
            * (tube_details[f"chain_{quantity}"] - tube_details[f"hf_{quantity}"])
            / tube_details[f"hf_{quantity}"]
        )

    return results, tube_details


def summarize(results, tube_details):
    """Error and cost summary by condition set and cation."""

    def summary(group):
        stage_error = group["stage_percent_error"].abs()
        chain_error = group["chain_percent_error"].abs()
        return pd.Series(
            {
                "n_points": len(group),
                "stage_surrogate_MAPE_%": stage_error.mean(),
                "stage_surrogate_max_APE_%": stage_error.max(),
                "tube_chain_MAPE_%": chain_error.mean(),
                "tube_chain_max_APE_%": chain_error.max(),
                "stage_solve_time_s": group["stage_solve_time_s"].median(),
                "chain_solve_time_s": group["chain_solve_time_s"].median(),
                "hf_warm_solve_time_s": group["hf_warm_solve_time_s"].median(),
                "chain_max_extrapolation": group["chain_extrapolation"].max(),
                "n_failed_stage": int(group["stage_flux"].isna().sum()),
                "n_failed_chain": int(group["chain_flux"].isna().sum()),
            }
        )

    summary_table = results.groupby(["set", "cation"]).apply(summary)
    return summary_table


def model_size_table(tube_surrogate, stage_surrogate):
    """Number of variables and constraints of each representation (one stage)."""
    sizes = {}

    m = build_stage_surrogate_flowsheet(1, 175, 6, stage_surrogate)
    sizes["Stage surrogate"] = (
        number_variables(m),
        number_total_constraints(m),
        degrees_of_freedom(m),
    )

    m = build_tube_surrogate_flowsheet(1, 175, 6, tube_surrogate)
    sizes["Tube surrogate chain"] = (
        number_variables(m),
        number_total_constraints(m),
        degrees_of_freedom(m),
    )

    try:  # the first-principles stage; unit models only (streams not connected)
        from prommis.nanofiltration.multi_component_diafiltration_stage import (
            MultiComponentDiafiltrationStageFlowsheet,
        )

        stage = MultiComponentDiafiltrationStageFlowsheet(
            cation_list=["Na"],
            anion_list=["Cl"],
            num_tubes=NUM_TUBES,
            inlet_flow_volume={"feed": 17, "diafiltrate": [1e-10] * 3 + [5, 1e-10]},
            inlet_concentration={
                "feed": {"Na": 175, "Cl": 175},
                "diafiltrate": {
                    "Na": [1e-10, 1e-10, 1e-10, 10, 1e-10],
                    "Cl": [1e-10, 1e-10, 1e-10, 10, 1e-10],
                },
            },
            non_Donnan_partition_dict={"Na": 0.75, "Cl": 0.05},
        )
        m = stage.build_flowsheet()
        sizes["High-fidelity stage (unit models only)"] = (
            number_variables(m),
            number_total_constraints(m),
            degrees_of_freedom(m),
        )
    except Exception as e:
        print(f"High-fidelity model size not available: {e}")

    return pd.DataFrame(
        sizes, index=["variables", "constraints", "degrees of freedom"]
    ).T


def training_cost_table():
    """High-fidelity solves and PySMO training time behind each surrogate."""
    tube_points = len(
        pd.read_csv(os.path.join(HERE, "training_data/tube/single_salt/mixed_chlorides"))
    )
    stage_points = len(
        pd.read_csv(os.path.join(HERE, "training_data/stage/single_salt/mixed_chlorides"))
    )

    table = pd.DataFrame(
        {
            "high-fidelity runs": [tube_points, stage_points],
            "tube solves equivalent": [tube_points, stage_points * NUM_TUBES],
        },
        index=["Tube surrogate (single tube)", "Stage surrogate (5-tube stage)"],
    )

    times = []
    for scale in ("tube", "stage"):
        file = os.path.join(HERE, f"figures/{scale}/training_times.csv")
        if os.path.exists(file):
            t = pd.read_csv(file).set_index("model")["training_time_s"]
            times.append(t.get("Kriging", np.nan))
        else:
            times.append(np.nan)
    table["Kriging training time (s)"] = times
    return table


def plot_comparison(results):
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.8))
    colors = {"Na": "tab:blue", "Ca": "tab:orange", "La": "tab:green"}
    markers = {"training": "o", "test": "s"}

    for ax, model, title in (
        (axes[0], "stage", "Stage surrogate"),
        (axes[1], "chain", "Tube surrogate chain"),
    ):
        for (cation, label), group in results.groupby(["cation", "set"]):
            ax.scatter(
                group["hf_flux"],
                group[f"{model}_flux"],
                color=colors[cation],
                marker=markers[label],
                label=f"{cation} ({label})",
                alpha=0.8,
            )
        lims = [results["hf_flux"].min() * 0.9, results["hf_flux"].max() * 1.1]
        ax.plot(lims, lims, "k--", linewidth=1)
        ax.set_xlabel("High-fidelity stage-average cation flux")
        ax.set_ylabel("Surrogate stage-average cation flux")
        ax.set_title(title)
    axes[0].legend(fontsize=8)

    ax = axes[2]
    x = np.arange(3)
    for offset, model, name in ((-0.2, "stage", "Stage surrogate"), (0.2, "chain", "Tube chain")):
        mape = [
            results[results["cation"] == c][f"{model}_percent_error"].abs().mean()
            for c in ("Na", "Ca", "La")
        ]
        ax.bar(x + offset, mape, width=0.4, label=name)
    ax.set_xticks(x)
    ax.set_xticklabels(["Na", "Ca", "La"])
    ax.set_ylabel("Mean absolute percent error (%)")
    ax.set_title("Flux error against high-fidelity stage")
    ax.legend()

    plt.tight_layout()
    plt.savefig(f"{OUTPUT_FOLDER}/comparison_stage_flux.png", dpi=600)


