def build_stage_surrogate_flowsheet(valence, feed_conc, pressure, stage_surrogate):
    """Stage-scale flowsheet: one surrogate for the whole 5-tube stage."""
    m = ConcreteModel()
    m.fs = FlowsheetBlock(dynamic=False)

    # surrogate inputs
    m.fs.valence_cation = Var(initialize=valence, doc="Charge of cation in chloride salt")
    m.fs.feed_conc_cation = Var(
        initialize=feed_conc, doc="Feed concentration of cation or chloride salt"
    )
    m.fs.applied_pressure_tube_1 = Var(
        initialize=pressure, doc="Applied pressure of the first tube in stage"
    )

    # surrogate output
    m.fs.flux_cation = Var(
        initialize=1, doc="Stage-average solute flux of cation in chloride salt"
    )

    inputs_by_label = {
        "valency": m.fs.valence_cation,
        "feed_conc": m.fs.feed_conc_cation,
        "pressure": m.fs.applied_pressure_tube_1,
    }
    m.fs.stage_surrogate = SurrogateBlock()
    m.fs.stage_surrogate.build_model(
        stage_surrogate,
        input_vars=[inputs_by_label[label] for label in stage_surrogate.input_labels()],
        output_vars=[m.fs.flux_cation],
    )

    m.fs.valence_cation.fix(valence)
    m.fs.feed_conc_cation.fix(feed_conc)
    m.fs.applied_pressure_tube_1.fix(pressure)

    return m


def build_tube_surrogate_flowsheet(
    valence, feed_conc, pressure, tube_surrogate, num_tubes=NUM_TUBES, initialize=True
):
    """
    Tube-scale flowsheet: one surrogate per tube, connected with mass balances.
    The inputs of tubes 2 to num_tubes are computed from the upstream tube, so
    their bounds are relaxed; the solution is checked against the training
    bounds afterwards (see tube_input_extrapolation).
    """
    diafiltrate_flow = DIAFILTRATE_FLOW[valence]

    m = ConcreteModel()
    m.fs = FlowsheetBlock(dynamic=False)
    m.fs.tubes = RangeSet(1, num_tubes)

    m.fs.valence_cation = Var(initialize=valence, doc="Charge of cation in chloride salt")

    # tube inlet (after mixing with any diafiltrate), surrogate inputs
    m.fs.feed_flow = Var(m.fs.tubes, initialize=FEED_FLOW, doc="Tube feed flow, m3/h")
    m.fs.feed_conc_cation = Var(
        m.fs.tubes, initialize=feed_conc, doc="Tube feed cation concentration, mol/m3"
    )
    m.fs.applied_pressure = Var(m.fs.tubes, doc="Applied pressure per tube, bar")

    # surrogate outputs
    m.fs.flux_cation = Var(m.fs.tubes, initialize=1, doc="Tube-average cation flux")
    m.fs.log_water_flux = Var(
        m.fs.tubes, initialize=-4, doc="Log of tube-average water flux, m3/m2/h"
    )

    # tube outlets
    m.fs.water_flux = Var(m.fs.tubes, initialize=0.02, doc="Tube-average water flux")
    m.fs.retentate_flow = Var(
        m.fs.tubes, initialize=FEED_FLOW / 2, bounds=(1e-3, None), doc="m3/h"
    )
    m.fs.retentate_conc_cation = Var(
        m.fs.tubes, initialize=feed_conc, bounds=(0, None), doc="mol/m3"
    )

    inputs_by_label = {}
    outputs_by_label = {}
    m.fs.tube_surrogate = SurrogateBlock(m.fs.tubes)
    for i in m.fs.tubes:
        inputs_by_label = {
            "valency": m.fs.valence_cation,
            "feed_conc": m.fs.feed_conc_cation[i],
            "pressure": m.fs.applied_pressure[i],
            "feed_flow": m.fs.feed_flow[i],
        }
        outputs_by_label = {
            "ion_flux": m.fs.flux_cation[i],
            "log_water_flux": m.fs.log_water_flux[i],
        }
        m.fs.tube_surrogate[i].build_model(
            tube_surrogate,
            input_vars=[inputs_by_label[l] for l in tube_surrogate.input_labels()],
            output_vars=[outputs_by_label[l] for l in tube_surrogate.output_labels()],
        )
        if i > 1:  # computed inputs: relax the training bounds, check afterwards
            m.fs.feed_flow[i].setlb(None)
            m.fs.feed_flow[i].setub(None)
            m.fs.feed_conc_cation[i].setlb(None)
            m.fs.feed_conc_cation[i].setub(None)

    # diafiltrate stream (zero except at DIAFILTRATE_TUBE)
    def _diafiltrate_flow(i):
        return diafiltrate_flow if i == DIAFILTRATE_TUBE else 0

    # connections between tubes: mixing of upstream retentate and diafiltrate
    def _feed_flow_balance(blk, i):
        if i == 1:
            return Constraint.Skip
        return blk.feed_flow[i] == blk.retentate_flow[i - 1] + _diafiltrate_flow(i)

    m.fs.feed_flow_balance = Constraint(m.fs.tubes, rule=_feed_flow_balance)

    def _feed_conc_balance(blk, i):
        if i == 1:
            return Constraint.Skip
        return blk.feed_conc_cation[i] * blk.feed_flow[i] == (
            blk.retentate_flow[i - 1] * blk.retentate_conc_cation[i - 1]
            + _diafiltrate_flow(i) * DIAFILTRATE_CONC
        )

    m.fs.feed_conc_balance = Constraint(m.fs.tubes, rule=_feed_conc_balance)

    # tube water flux and mass balances
    m.fs.water_flux_equation = Constraint(
        m.fs.tubes, rule=lambda blk, i: blk.water_flux[i] == exp(blk.log_water_flux[i])
    )
    m.fs.overall_balance = Constraint(
        m.fs.tubes,
        rule=lambda blk, i: blk.retentate_flow[i]
        == blk.feed_flow[i] - MEMBRANE_AREA * blk.water_flux[i],
    )
    m.fs.cation_balance = Constraint(
        m.fs.tubes,
        rule=lambda blk, i: blk.retentate_flow[i] * blk.retentate_conc_cation[i]
        == blk.feed_flow[i] * blk.feed_conc_cation[i]
        - MEMBRANE_AREA * blk.flux_cation[i],
    )

    m.fs.stage_average_flux = Expression(
        expr=sum(m.fs.flux_cation[i] for i in m.fs.tubes) / num_tubes
    )

    # specifications: tube 1 feed and the applied pressures
    m.fs.valence_cation.fix(valence)
    m.fs.feed_flow[1].fix(FEED_FLOW)
    m.fs.feed_conc_cation[1].fix(feed_conc)
    for i in m.fs.tubes:
        m.fs.applied_pressure[i].fix(pressure - (i - 1) * PRESSURE_DROP)

    if initialize:
        initialize_tube_flowsheet(m, tube_surrogate, valence, feed_conc, pressure)

    return m


def initialize_tube_flowsheet(m, tube_surrogate, valence, feed_conc, pressure):
    """Initializes by propagating the surrogates and mass balances tube by tube."""
    flow_in, conc_in = FEED_FLOW, feed_conc
    for i in m.fs.tubes:
        inputs = pd.DataFrame(
            [
                {
                    "valency": valence,
                    "feed_conc": conc_in,
                    "pressure": pressure - (i - 1) * PRESSURE_DROP,
                    "feed_flow": flow_in,
                }
            ]
        )
        outputs = tube_surrogate.evaluate_surrogate(inputs)
        flux = float(outputs["ion_flux"].iloc[0])
        log_water_flux = float(outputs["log_water_flux"].iloc[0])
        water_flux = np.exp(log_water_flux)
        flow_out = max(flow_in - MEMBRANE_AREA * water_flux, 1e-2)
        conc_out = max((flow_in * conc_in - MEMBRANE_AREA * flux) / flow_out, 0)

        m.fs.feed_flow[i].set_value(flow_in)
        m.fs.feed_conc_cation[i].set_value(conc_in)
        m.fs.flux_cation[i].set_value(flux)
        m.fs.log_water_flux[i].set_value(log_water_flux)
        m.fs.water_flux[i].set_value(water_flux)
        m.fs.retentate_flow[i].set_value(flow_out)
        m.fs.retentate_conc_cation[i].set_value(conc_out)

        flow_in, conc_in = flow_out, conc_out
        if i + 1 == DIAFILTRATE_TUBE:
            d_flow = DIAFILTRATE_FLOW[valence]
            conc_in = (flow_in * conc_in + d_flow * DIAFILTRATE_CONC) / (flow_in + d_flow)
            flow_in = flow_in + d_flow


def solve_flowsheet(m):
    solver = SolverFactory("ipopt")
    start = time.perf_counter()
    results = solver.solve(m, tee=False)
    solve_time = time.perf_counter() - start
    assert_optimal_termination(results)
    return solve_time


def tube_input_extrapolation(m, tube_surrogate):
    """Largest relative distance of a tube input outside the surrogate bounds."""
    bounds = tube_surrogate.input_bounds()
    worst = 0.0
    for i in m.fs.tubes:
        for label, var in (
            ("feed_conc", m.fs.feed_conc_cation[i]),
            ("feed_flow", m.fs.feed_flow[i]),
            ("pressure", m.fs.applied_pressure[i]),
        ):
            lo, hi = bounds[label]
            x = value(var)
            worst = max(worst, (lo - x) / (hi - lo), (x - hi) / (hi - lo))
    return max(worst, 0.0)


